async function fetchAvailableModels(settings, target) {
  const apiKey = target === "embedding" ? getEffectiveEmbeddingApiKey(settings) : getChatApiKey(settings);
  const url = target === "embedding" ? getEmbeddingModelsUrl(settings) : getChatModelsUrl(settings);
  const response = await (0, import_obsidian15.requestUrl)({
    url,
    method: "GET",
    headers: buildOpenAIHeaders(apiKey)
  });
  if (response.status < 200 || response.status >= 300) {
    throw new Error(`Server returned ${response.status}`);
  }
  const data = response.json;
  if (!(data == null ? void 0 : data.data) || !Array.isArray(data.data)) {
    throw new Error("Unexpected response format");
  }
  return data.data.map((model) => model.id).filter((id) => Boolean(id)).sort();
}
