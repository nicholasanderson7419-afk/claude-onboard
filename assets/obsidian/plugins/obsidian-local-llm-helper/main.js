async function tavilySearch(query, topic, plugin) {
  const body = {
    query,
    topic,
    max_results: 5,
    search_depth: "basic",
    include_answer: false
  };
  if (topic === "news") {
    body.time_range = "day";
  }
  const response = await (0, import_obsidian15.requestUrl)({
    url: "https://api.tavily.com/search",
    method: "POST",
    headers: {
      "Authorization": `Bearer ${plugin.settings.tavilyApiKey}`,
      "Content-Type": "application/json"
    },
    body: JSON.stringify(body)
  });
  if (response.status !== 200) {
    throw new Error("Tavily search failed: " + response.status);
  }
  const results = response.json.results;
  return results.map(
    (result) => `${result.title}
${result.content}
Source: ${result.url}

`
  ).join("");
}
function buildSearxngSearchUrl(query, topic, instanceUrl) {
  const normalizedInstanceUrl = normalizeSearxngInstanceUrl(instanceUrl);
  const searchUrl = new URL(normalizedInstanceUrl);
  const basePath = searchUrl.pathname.replace(/\/+$/, "");
  searchUrl.pathname = basePath.endsWith("/search") ? basePath : `${basePath}/search`;
  searchUrl.search = "";
  searchUrl.hash = "";
  searchUrl.searchParams.set("q", query);
  searchUrl.searchParams.set("format", "json");
  if (topic === "news") {
    searchUrl.searchParams.set("categories", "news");
    searchUrl.searchParams.set("time_range", "day");
  }
  return searchUrl.toString();
}
function formatSearxngResults(response) {
  const results = response.results || [];
  return results.filter((result) => result.url && result.title).slice(0, 5).map((result) => {
    const content = result.content ? `
${result.content}` : "";
    const engines = result.engines && result.engines.length > 0 ? `
Engines: ${result.engines.join(", ")}` : "";
    const published = result.publishedDate || result.published_date;
    const publishedLine = published ? `
Published: ${published}` : "";
    return `${result.title}${content}
Source: ${result.url}${engines}${publishedLine}

`;
  }).join("");
}
function getSearchErrorMessage(error, fallback) {
  return error instanceof Error ? error.message : fallback;
}
async function searxngSearch(query, topic, plugin) {
  const response = await (0, import_obsidian15.requestUrl)({
    url: buildSearxngSearchUrl(query, topic, plugin.settings.searxngInstanceUrl),
    method: "GET",
    headers: {
      "Accept": "application/json"
    }
  });
  if (response.status === 403) {
    throw new Error("SearXNG search failed: JSON output is not enabled or access is forbidden for this instance. Add json to search.formats in settings.yml.");
  }
  if (response.status !== 200) {
    throw new Error("SearXNG search failed: " + response.status);
  }
  const searchResponse = response.json;
  if (!searchResponse || typeof searchResponse !== "object") {
    throw new Error("SearXNG search failed: the instance did not return a JSON response.");
  }
  if (searchResponse.error) {
    throw new Error("SearXNG search failed: " + searchResponse.error);
  }
  const context = formatSearxngResults(searchResponse);
  if (!context) {
    throw new Error("SearXNG search returned no usable results.");
  }
  return context;
}
async function processWebSearch(query, plugin) {
  const provider = plugin.settings.searchProvider;
  if (provider === "tavily" && !plugin.settings.tavilyApiKey) {
    new import_obsidian15.Notice("Please set your Tavily API key in settings");
    return;
  }
  if (provider === "brave" && !plugin.settings.braveSearchApiKey) {
    new import_obsidian15.Notice("Please set your Brave Search API key in settings");
    return;
  }
  if (provider === "searxng" && !plugin.settings.searxngInstanceUrl) {
    new import_obsidian15.Notice("Please set your SearXNG instance URL in settings");
    return;
  }
  new import_obsidian15.Notice("Searching the web...");
  try {
    let context;
    if (provider === "tavily") {
      context = await tavilySearch(query, "general", plugin);
    } else if (provider === "searxng") {
      context = await searxngSearch(query, "general", plugin);
    } else {
      const response = await (0, import_obsidian15.requestUrl)({
        url: `https://api.search.brave.com/res/v1/web/search?q=${encodeURIComponent(query)}&count=5&summary=1&extra_snippets=1&text_decorations=1&result_filter=web,discussions,faq,news&spellcheck=1`,
        method: "GET",
        headers: {
          "Accept": "application/json",
          "Accept-Encoding": "gzip",
          "X-Subscription-Token": plugin.settings.braveSearchApiKey
        }
      });
      if (response.status !== 200) {
        throw new Error("Search failed: " + response.status);
      }
      const searchResults = response.json.web.results;
      context = searchResults.map((result) => {
        let snippets = result.extra_snippets ? "\nAdditional Context:\n" + result.extra_snippets.join("\n") : "";
        return `${result.title}
${result.description}${snippets}
Source: ${result.url}

`;
      }).join("");
    }
    void processText(
      `Search results for "${query}":

${context}`,
      "Summarize these search results concisely. Use bullet points for key facts and cite sources inline as [Source](url).",
      plugin
    );
  } catch (error) {
    console.error("Web search error:", error);
    new import_obsidian15.Notice(getSearchErrorMessage(error, "Web search failed. Check console for details."));
  }
}
